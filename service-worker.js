self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    // Warm the same offline assets, but in small batches. Parallel requests
    // for every question image at once can overwhelm slower devices.
    for (let i = 0; i < APP_SHELL.length; i += 6) {
      await Promise.all(APP_SHELL.slice(i, i + 6).map(async path => {
        try {
          const request = new Request(new URL(path, self.registration.scope).href, { cache: 'reload' });
          const response = await fetch(request);
          if (response.ok) await cache.put(request, response.clone());
        } catch (_) { /* Requested files cache as they are used. */ }
      }));
    }
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', event => event.waitUntil((async () => {
  const keys = await caches.keys();
  await Promise.all(keys.filter(k => k.startsWith(CACHE_PREFIX) && k !== CACHE_NAME).map(k => caches.delete(k)));
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  // WebLLM配布JSを取得した場合のみ、オフライン再起動向けにキャッシュ。
  // モデル本体のキャッシュは WebLLM 自身が管理。第三者サイトの一般通信は対象外。
  if ((url.hostname === 'esm.run' || url.hostname === 'cdn.jsdelivr.net') &&
      (request.destination === 'script' || /\.(?:m?js)(?:$|\?)/i.test(url.pathname))) {
    event.respondWith((async () => {
      const cache = await caches.open('kotoba-quest-qwen-v257-cdn-js');
      const cached = await cache.match(request);
      if (cached) return cached;
      const response = await fetch(request);
      if (response && response.ok && response.type !== 'opaque') {
        try { await cache.put(request, response.clone()); } catch (_) {}
      }
      return response;
    })());
    return;
  }
  if (url.origin === self.location.origin) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      // Large, immutable dialogue portraits and sound effects should be served
      // from local cache on subsequent visits. Preserve network-first for code.
      const stableMedia = /\/(?:images\/story|sounds|voice\/articulation)\//.test(url.pathname);
      if (stableMedia) {
        const cachedMedia = await cache.match(request,{ignoreSearch:true});
        if (cachedMedia) return cachedMedia;
      }
      try {
        const response = await fetch(request);
        if (response && response.ok && response.type !== 'opaque') {
          try { await cache.put(request, response.clone()); } catch (_) {}
        }
        return response;
      } catch (error) {
        const cached = await cache.match(request, { ignoreSearch: true });
        if (cached) return cached;
        if (request.mode === 'navigate') {
          const shell = await cache.match(new URL('index.html', self.registration.scope).href, { ignoreSearch: true });
          if (shell) return shell;
        }
        throw error;
      }
    })());
  }
});
